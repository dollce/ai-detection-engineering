"""Generate project-local Codex MCP configuration without changing user settings.

Run from any directory. Existing .codex/config.toml files are never overwritten.
Only the interactive Codex CLI uses these servers; pipeline reasoning calls are
isolated from project and user configuration by orchestration/codex_llm.py.
"""

import argparse
import json
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def render_config(repo_root: Path, include_cribl: bool = False, siem_mode: str = "elastic") -> str:
    """Render Codex TOML using escaped strings and explicit server working dirs."""
    if siem_mode not in {"elastic", "splunk", "both"}:
        raise ValueError(f"Unsupported SIEM mode: {siem_mode}")
    repo_root = repo_root.resolve()
    quoted_root = json.dumps(str(repo_root), ensure_ascii=False)
    lines = [
        "# Generated by pipeline/configure_codex.py for this checkout/worktree.",
        "# Codex loads project config only after the project is trusted.",
        "# Keep local credentials and custom settings out of version control.",
        "",
        "[mcp_servers]",
        "",
    ]
    if siem_mode in {"elastic", "both"}:
        lines.extend([
            "[mcp_servers.elasticsearch]",
            'command = "docker"',
            'args = ["run", "--rm", "-i", "--network", "blue-team-lab",',
            '        "-e", "ES_URL=http://elastic:changeme@elasticsearch:9200",',
            '        "docker.elastic.co/mcp/elasticsearch"]',
            "",
        ])
    if include_cribl and shutil.which("node"):
        lines.extend([
            "[mcp_servers.cribl]",
            'command = "node"',
            'args = ["./cribl/mcp-server/index.js"]',
            f"cwd = {quoted_root}",
            "",
            "[mcp_servers.cribl.env]",
            'CRIBL_URL = "http://localhost:9000"',
            'CRIBL_USER = "admin"',
            'CRIBL_PASS = "admin"',
            "",
        ])
    if shutil.which("npx"):
        lines.extend([
            "# Export this token in the launching shell; do not put it in this file.",
            "[mcp_servers.github]",
            'command = "npx"',
            'args = ["-y", "@modelcontextprotocol/server-github"]',
            'env_vars = ["GITHUB_PERSONAL_ACCESS_TOKEN"]',
            f"cwd = {quoted_root}",
            "",
        ])
    return "\n".join(lines)


def write_config(repo_root: Path, include_cribl: bool = False, siem_mode: str = "elastic") -> bool:
    """Create config once, returning False if the user already has one."""
    rendered = render_config(repo_root, include_cribl, siem_mode)
    config_path = repo_root / ".codex" / "config.toml"
    config_path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    try:
        with config_path.open("x", encoding="utf-8") as stream:
            stream.write(rendered)
    except FileExistsError:
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--siem-mode", choices=("elastic", "splunk", "both"), default="elastic",
                        help="Register Elasticsearch only when the selected lab includes it")
    parser.add_argument("--cribl", action="store_true", help="Include the local Cribl MCP server")
    args = parser.parse_args()
    created = write_config(REPO_ROOT, args.cribl, args.siem_mode)
    if created:
        print("Codex MCP config generated at .codex/config.toml")
        if args.cribl and not shutil.which("node"):
            print("Node.js unavailable: Cribl server omitted; add it after installing Node.js.")
        if not shutil.which("npx"):
            print("npx unavailable: GitHub server omitted; add it after installing Node.js/npm.")
    else:
        print(".codex/config.toml already exists (not overwritten)")
    print("Trust this project in Codex, then verify servers with: codex mcp list")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
